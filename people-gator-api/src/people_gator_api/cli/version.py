from importlib.metadata import PackageNotFoundError, version
from pathlib import Path
import subprocess


def _run_git(*args: str, repo_root: Path) -> str | None:
    try:
        result = subprocess.run(
            ["git", *args],
            cwd=repo_root,
            capture_output=True,
            text=True,
            timeout=2,
            check=True,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return result.stdout.strip()


def write_version_file() -> None:
    package_root = Path(__file__).resolve().parents[1]
    repo_root = package_root.parents[2]
    try:
        package_version = version("people-gator-api")
    except PackageNotFoundError:
        package_version = "0.0.0+unknown"

    git_commit = _run_git("rev-parse", "--short", "HEAD", repo_root=repo_root)
    status = _run_git("status", "--porcelain", repo_root=repo_root)
    generated_path = package_root / "_version.py"
    generated_name = str(generated_path.relative_to(repo_root))
    dirty_paths = [line for line in (status or "").splitlines() if generated_name not in line]
    generated_path.write_text(
        "\n".join(
            [
                "# Generated by people-gator-version; do not edit.",
                f"GENERATED_PACKAGE_VERSION = {package_version!r}",
                f"GENERATED_GIT_COMMIT = {git_commit!r}",
                f"GENERATED_GIT_DIRTY = {bool(dirty_paths)!r}",
                "",
            ]
        ),
        encoding="utf-8",
    )


if __name__ == "__main__":
    write_version_file()